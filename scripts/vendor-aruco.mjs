// Converts js-aruco2 (a pre-module script that attaches to `this`) into one ES module
// that modern bundlers accept. Only the parts we use: image ops, detector, 4x4 dictionary.
// Re-run after upgrading js-aruco2:  node scripts/vendor-aruco.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = "node_modules/js-aruco2";
const { version } = JSON.parse(readFileSync(`${src}/package.json`, "utf8"));
const part = (file) =>
  readFileSync(`${src}/src/${file}`, "utf8")
    // dependencies come from the shared scope below, never from require()
    .replace("this.CV || require('./cv').CV", "this.CV")
    .replace("this.AR || require('../aruco').AR", "this.AR");

const out = `// GENERATED by scripts/vendor-aruco.mjs from js-aruco2@${version} — do not edit.
// js-aruco2: MIT, (c) 2020 Damiano Falcioni, (c) 2011 Juan Mellado.
// ARUCO_4X4_1000 dictionary: extracted from OpenCV contrib (Apache-2.0 / BSD), as shipped in js-aruco2.
/* eslint-disable */
// @ts-nocheck
const scope = {};
(function () {
${part("cv.js")}
}).call(scope);
(function () {
${part("aruco.js")}
}).call(scope);
(function () {
${part("dictionaries/aruco_4x4_1000.js")}
}).call(scope);
export const AR = scope.AR;
`;

if (/require\(/.test(out)) throw new Error("unexpected require() left in vendored source");
writeFileSync("lib/vendor/js-aruco2.js", out);
console.log(`wrote lib/vendor/js-aruco2.js (js-aruco2@${version}, ${out.length} bytes)`);
